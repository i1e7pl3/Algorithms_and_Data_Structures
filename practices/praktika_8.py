# Лабораторная работа 8. Сортировка вставками
# Берем очередной элемент и вставляем его в уже отсортированную левую часть.

print("Исходный массив введите через пробел")
a = list(map(int, input().split()))
n = len(a)
print("Было:", a)

# Задание: сортировка вставками
i = 1
while i < n:
    tekushiy = a[i]
    j = i - 1
    print("--- вставляем", tekushiy, "---")
    print("  отсортированная часть:", a[:i])
    while j >= 0 and a[j] > tekushiy:
        print("  сдвигаем", a[j], "вправо")
        a[j + 1] = a[j]
        j = j - 1
        print("  сейчас:", a)
    a[j + 1] = tekushiy
    print("  вставили на позицию", j + 1, "->", a)
    i = i + 1

print("Отсортировано:", a)
