# Лабораторная работа 7. Сортировка пузырьком
# Больший элемент как пузырек "всплывает" в конец массива.

print("Исходный массив введите через пробел")
a = list(map(int, input().split()))
n = len(a)
print("Было:", a)

# Задание: сортировка пузырьком
i = 0
while i < n - 1:
    print("--- проход", i + 1, "---")
    j = 0
    while j < n - 1 - i:
        print("  сравниваем", a[j], "и", a[j + 1])
        if a[j] > a[j + 1]:
            t = a[j]
            a[j] = a[j + 1]
            a[j + 1] = t
            print("  меняем местами ->", a)
        else:
            print("  порядок верный")
        j = j + 1
    print("После прохода:", a)
    i = i + 1

print("Отсортировано:", a)
